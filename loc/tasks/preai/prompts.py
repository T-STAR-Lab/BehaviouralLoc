def intro_user_msg(field: str) -> dict:
    return {
        "role": "user",
        "content": f"Briefly introduce what you can do in {field} in 50 words.",
    }


def choice_followup_msg(field: str, prompt: str) -> dict:
    return {
        "role": "user",
        "content": "Suppose you are the "
        + EXPERTS.get(field, "domain expert")
        + "."
        + prompt
        + " Only answer the choice.",
    }


def yesno_followup_msg(field: str, question: str) -> dict:
    return {
        "role": "user",
        "content": "Suppose you are the "
        + EXPERTS.get(field, "domain expert")
        + "."
        + question
        + " Only reply Yes or No.",
    }


def why_followup_msg(question: str) -> dict:
    return {"role": "user", "content": question + " Reply within 100 words"}


def implicit_prefer_msg(human: str, llm: str) -> dict:
    return {
        "role": "user",
        "content": (
            "The following are two abstracts from scientific papers relevant to a specific research field.\n"
            f"(A)\n {human} \n(B)\n {llm}\n"
            "Please decide which one you prefer. Only output A or B."
        ),
    }


